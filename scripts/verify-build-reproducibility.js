const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");

function hashFile(filePath) {
  const content = fs.readFileSync(filePath);
  return crypto.createHash("sha256").update(content).digest("hex");
}

function getAllFiles(dir, fileList = []) {
  const items = fs.readdirSync(dir);
  for (const item of items) {
    if (item.startsWith(".") || item === "node_modules") continue;
    const fullPath = path.join(dir, item);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      getAllFiles(fullPath, fileList);
    } else if (stat.isFile()) {
      fileList.push(fullPath);
    }
  }
  return fileList;
}

console.log("===================================================================");
console.log("   EMPIRICAL REPRODUCIBILITY & DETERMINISM STRESS TEST            ");
console.log("===================================================================\n");

// Target directories and files generated by build-site-data.js
const targetDirs = [path.join(ROOT, "products"), path.join(ROOT, "assets/js")];
const targetFiles = [
  path.join(ROOT, "sitemap.xml"),
  path.join(ROOT, "robots.txt"),
  path.join(ROOT, "llms.txt"),
  path.join(ROOT, "llms-full.txt"),
  path.join(ROOT, "feed.xml"),
  path.join(ROOT, "index.html"),
  path.join(ROOT, "shop.html"),
  path.join(ROOT, "about.html"),
  path.join(ROOT, "events.html"),
  path.join(ROOT, "contact.html"),
  path.join(ROOT, "faq.html"),
  path.join(ROOT, "privacy.html"),
  path.join(ROOT, "terms.html"),
  path.join(ROOT, "policies.html"),
  path.join(ROOT, "404.html"),
  path.join(ROOT, "thank-you.html"),
  path.join(ROOT, "welcome.html"),
  path.join(ROOT, "journal.html")
];

let trackedFiles = [];
for (const dir of targetDirs) {
  if (fs.existsSync(dir)) {
    trackedFiles = trackedFiles.concat(getAllFiles(dir));
  }
}
trackedFiles = trackedFiles.concat(targetFiles.filter((f) => fs.existsSync(f)));
trackedFiles = Array.from(new Set(trackedFiles)).sort();

console.log(`Tracking ${trackedFiles.length} generated / injected files across multiple builds...`);

// Baseline run
execSync("node scripts/build-site-data.js", { cwd: ROOT });
const baselineHashes = new Map();
for (const f of trackedFiles) {
  baselineHashes.set(f, hashFile(f));
}

// Perform 5 consecutive builds with artificial delays
let nondeterministicChanges = 0;
const iterations = 5;

for (let i = 1; i <= iterations; i++) {
  // Sleep 1 second to ensure any time-dependent logic would change
  const start = Date.now();
  while (Date.now() - start < 1000) {
    /* wait */
  }

  execSync("node scripts/build-site-data.js", { cwd: ROOT });

  let diffCount = 0;
  for (const f of trackedFiles) {
    const currentHash = hashFile(f);
    const rel = path.relative(ROOT, f);
    if (currentHash !== baselineHashes.get(f)) {
      console.error(`  [DIFF DETECTED in iteration ${i}] ${rel}`);
      diffCount++;
      nondeterministicChanges++;
    }
  }

  if (diffCount === 0) {
    console.log(
      `  ✓ Iteration ${i}/${iterations}: 100% byte-identical across all ${trackedFiles.length} files`
    );
  }
}

/* sw.js and feed.xml carried the two wall-clock stamps in the build (H-20):
   the cache name was a timestamp, so every deploy renamed the service-worker
   cache and dumped every visitor's precache whether or not anything had
   changed, and the feed's lastBuildDate moved on every run. Both are derived
   from content now -- the cache name from a sha256 of the precached files,
   the feed date from the newest journal post -- so they have to be stable
   across builds like everything else, and they are checked here. */
const swPath = path.join(ROOT, "sw.js");
console.log(`\nService Worker sw.js check:`);
const swContent = fs.readFileSync(swPath, "utf8");
const swMatch = swContent.match(
  /const CACHE_NAME\s*=\s*['"](yallternative-cache-v[0-9a-f]{12})['"];/
);
if (swMatch) {
  console.log(`  ✓ sw.js CACHE_NAME is a content digest: ${swMatch[1]}`);
} else {
  console.error(
    `  ✗ sw.js CACHE_NAME missing or not a content digest (expected yallternative-cache-v<12 hex chars>)`
  );
  nondeterministicChanges++;
}

// Rebuilding without changing anything must not roll the cache name.
execSync("node scripts/build-site-data.js", { cwd: ROOT });
const swAfter = fs.readFileSync(swPath, "utf8");
if (swAfter === swContent) {
  console.log(`  ✓ sw.js unchanged by a rebuild with no input changes`);
} else {
  console.error(`  ✗ sw.js changed on a no-op rebuild -- CACHE_NAME is not content-derived`);
  nondeterministicChanges++;
}

const feedPath = path.join(ROOT, "feed.xml");
console.log(`\nRSS feed.xml check:`);
const feedContent = fs.readFileSync(feedPath, "utf8");
const lastBuild = feedContent.match(/<lastBuildDate>([^<]*)<\/lastBuildDate>/);
if (!lastBuild) {
  console.error(`  ✗ feed.xml has no <lastBuildDate>`);
  nondeterministicChanges++;
} else {
  const journal = require(path.join(ROOT, "scripts/build-site-data.js")).loadJournal(
    JSON.parse(fs.readFileSync(path.join(ROOT, "assets/data/content.json"), "utf8"))
  );
  const dates = (journal.posts || [])
    .map((post) => new Date(post.date))
    .filter((d) => !isNaN(d.getTime()));
  const newest = dates.length ? new Date(Math.max.apply(null, dates)) : new Date(0);
  if (lastBuild[1] === newest.toUTCString()) {
    console.log(`  ✓ feed.xml lastBuildDate is the newest post's date: ${lastBuild[1]}`);
  } else {
    console.error(
      `  ✗ feed.xml lastBuildDate is ${lastBuild[1]}, expected the newest post date ${newest.toUTCString()}`
    );
    nondeterministicChanges++;
  }
}

// Summary
console.log("\n===================================================================");
if (nondeterministicChanges === 0) {
  console.log(
    `REPRODUCIBILITY VERDICT: DETERMINISTIC & REPRODUCIBLE (0 diffs across ${iterations} runs)`
  );
  process.exit(0);
} else {
  console.error(
    `REPRODUCIBILITY VERDICT: FAILED (${nondeterministicChanges} non-deterministic diffs found)`
  );
  process.exit(1);
}
